export async function POST(req: NextRequest) {
  try {
    const body = await req.json().catch(() => null);
    const message: string | undefined = body?.message;
    const history: HistoryMsg[] = Array.isArray(body?.history) ? body.history : [];

    if (!message || typeof message !== "string" || message.trim().length === 0) {
      return NextResponse.json(
        { error: "Поле message обязательно и должно быть непустой строкой." },
        { status: 400 }
      );
    }

    // Build chat history. Keep last 8 messages for token economy.
    const trimmed = history.slice(-8);

    const messages: { role: "system" | "user" | "assistant"; content: string }[] = [
      { role: "system", content: SYSTEM_PROMPT },
      ...trimmed.map((m) => ({
        role: m.role === "assistant" ? ("assistant" as const) : ("user" as const),
        content: m.content,
      })),
      { role: "user", content: message },
    ];

    const zai = await ZAI.create();
    const completion = await zai.chat.completions.create({
      messages,
      thinking: { type: "disabled" },
    });

    const reply: string =
      completion?.choices?.[0]?.message?.content ??
      completion?.content ??
      "";

    if (!reply) {
      return NextResponse.json(
        { error: "Стилист пока не может ответить. Попробуйте ещё раз." },
        { status: 502 }
      );
    }

    return NextResponse.json({ reply });
  } catch (err) {
    console.error("[style-assistant] error:", err);
    return NextResponse.json(
      {
        error:
          "Стилист сейчас недоступен. Позвоните нам на +7 (960) 795 93 69 — поможем подобрать образ.",
      },
      { status: 500 }
    );
  }
}
